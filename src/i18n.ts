const dictionaries = { en, de };
export type Strings = typeof en;

/** "Mon, 19.10." style short date for a "YYYY-MM-DD" day. */
export const formatDay = (day: string, lang: Lang) => new Intl.DateTimeFormat(lang === "de" ? "de-DE" : "en-GB", {
  weekday: "short", day: "numeric", month: "numeric", timeZone: "UTC",
}).format(new Date(`${day}T00:00:00Z`));

export const formatMonth = (year: number, month: number, lang: Lang) => new Intl.DateTimeFormat(lang === "de" ? "de-DE" : "en-GB", {
  month: "long", year: "numeric", timeZone: "UTC",
}).format(new Date(Date.UTC(year, month, 1)));

const STORAGE_KEY = "lang";
const deviceLang = (): Lang => (getLocales()[0]?.languageCode === "de" ? "de" : "en");

let current: Lang = deviceLang();
const listeners = new Set<() => void>();

/** Strings for the current language; also usable outside React (e.g. error messages). */
export const strings = () => dictionaries[current];

export function setLang(lang: Lang) {
  if (lang === current) return;
  current = lang;
  listeners.forEach((l) => l());
  AsyncStorage.setItem(STORAGE_KEY, lang).catch(() => undefined);
}

/** Applies a language chosen earlier in the app (overrides the device language). */
export async function loadSavedLang() {
  const saved = await AsyncStorage.getItem(STORAGE_KEY).catch(() => null);
  if (saved === "en" || saved === "de") setLang(saved);
}

const subscribe = (l: () => void) => { listeners.add(l); return () => { listeners.delete(l); }; };
const getLang = () => current;

/** Re-renders the component when the language changes. */
export function useI18n() {
  const lang = useSyncExternalStore(subscribe, getLang, getLang);
  return { lang, t: dictionaries[lang] };
}
