// Lookup table and checks for the kitten's facts (src/mascot/facts.ts).
//   node scripts/facts-index.ts                 validate, then regenerate docs/mascot-facts-index.md and docs/mascot-facts.md
//   node scripts/facts-index.ts --check         validate only; also fails if the generated docs are stale
//   node scripts/facts-index.ts find <word...>  facts whose tag, topic or text contains every word (either language)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { FACTS } from "../src/mascot/facts.ts";

const TITLES: Record<string, string> = {
  cycle: "Your cycle", pill: "The pill", minipill: "Minipill", contraception: "Other contraception", emergency: "Emergency contraception",
  intimate: "Intimate health", sexual: "Sexual health", screening: "Screening and cancer awareness", conditions: "Conditions",
  pregnancy: "Pregnancy", pelvic: "Pelvic floor and bladder", menopause: "Menopause, bones and HRT",
};
const MAX_LEN = 200; // one speech bubble
const INDEX = new URL("../docs/mascot-facts-index.md", import.meta.url);
const LIST = new URL("../docs/mascot-facts.md", import.meta.url);
const [cmd, ...words] = process.argv.slice(2);

if (cmd === "find") {
  const want = words.map((w) => w.toLowerCase());
  const hits = FACTS.filter((f) => want.every((w) => `${f.topic} ${f.tag} ${f.en} ${f.de}`.toLowerCase().includes(w)));
  for (const f of hits) console.log(`${f.topic}/${f.tag}: ${f.en}`);
  console.log(`${hits.length} of ${FACTS.length}`);
  process.exit(0);
}

// ---------- Checks ----------
const problems: string[] = [];
const texts = new Map<string, string>();
FACTS.forEach((f, i) => {
  const at = `fact ${i + 1} (${f.tag})`;
  if (!TITLES[f.topic]) problems.push(`${at}: unknown topic "${f.topic}"`);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(f.tag)) problems.push(`${at}: tag must be kebab-case`);
  if (!f.en || !f.de) problems.push(`${at}: needs both English and German text`);
  if (f.en.length > MAX_LEN || f.de.length > MAX_LEN) problems.push(`${at}: text longer than ${MAX_LEN} characters`);
  if (!f.source || !/^https:\/\//.test(f.url)) problems.push(`${at}: needs a source name and an https URL`);
  const key = f.en.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
  if (texts.has(key)) problems.push(`${at}: same English text as ${texts.get(key)}`);
  texts.set(key, f.tag);
});
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

// ---------- Generated docs ----------
const byTopic = Object.keys(TITLES).map((topic) => ({ topic, facts: FACTS.filter((f) => f.topic === topic) })).filter((g) => g.facts.length);

const tagLine = (facts: typeof FACTS) => {
  const counts = new Map<string, number>();
  for (const f of facts) counts.set(f.tag, (counts.get(f.tag) ?? 0) + 1);
  return [...counts].map(([tag, n]) => (n > 1 ? `${tag}×${n}` : tag)).join(" · ");
};

const index = `# Mascot facts: lookup table

Generated by \`node scripts/facts-index.ts\` from [src/mascot/facts.ts](../src/mascot/facts.ts). Don't edit by hand.

${FACTS.length} facts. Each fact has a **tag**: a short slug for its subject. Below, every tag per topic, so you can see what's covered without reading the facts.

## Adding a fact
1. Read this file (it's short). Look for your subject's tag, e.g. \`pill-missed\`, \`herpes-pregnancy\`.
2. Tag already there? Add the fact anyway if it says something different or is worded differently. Near-duplicates are fine and cheaper than checking each one. \`node scripts/facts-index.ts find <word>\` lists the matching facts if you want to look.
3. Add \`{ topic, tag, ...source, en, de }\` at the end of \`FACTS\` in facts.ts. Sources are small helpers at the top (\`nhs()\`, \`who()\`, \`bund()\`, \`fp()\`) or a plain \`{ source, url }\`. Take the wording from the page you fetched, not from memory.
4. Run \`node scripts/facts-index.ts\`. It checks the fields (both languages, texts up to ${MAX_LEN} characters, https source, no identical text twice) and regenerates this file and [mascot-facts.md](mascot-facts.md).

${byTopic.map((g) => `## ${TITLES[g.topic]} (\`${g.topic}\`, ${g.facts.length})\n${tagLine(g.facts)}`).join("\n\n")}
`;

const list = `# Mascot facts: full list

Generated by \`node scripts/facts-index.ts\` from [src/mascot/facts.ts](../src/mascot/facts.ts). ${FACTS.length} facts the kitten can share ("Did you know? …"), each with the page it comes from. German texts are in facts.ts. The lookup table is in [mascot-facts-index.md](mascot-facts-index.md).

These are general facts, not personal medical advice.

${byTopic.map((g) => `## ${TITLES[g.topic]}\n\n${g.facts.map((f) => `- \`${f.tag}\`: ${f.en} ([${f.source}](${f.url}))`).join("\n")}`).join("\n\n")}
`;

if (cmd === "--check") {
  const stale = [[INDEX, index], [LIST, list]].filter(([url, text]) => !existsSync(url as URL) || readFileSync(url as URL, "utf8") !== text);
  if (stale.length) { console.error("docs are stale: run node scripts/facts-index.ts"); process.exit(1); }
  console.log(`${FACTS.length} facts OK, docs up to date`);
} else {
  writeFileSync(INDEX, index);
  writeFileSync(LIST, list);
  console.log(`${FACTS.length} facts OK; wrote docs/mascot-facts-index.md and docs/mascot-facts.md`);
}
